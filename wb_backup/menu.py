def welcome(config, *, restarted=False):
    title = 'Бот запущен.' if restarted else 'Архив Wildberries.'
    accounts = ', '.join(account.name for account in config.accounts)
    return (f'{title}\nКабинеты: {accounts}\n'
            f'Ежедневная отправка: {config.schedule:%H:%M} по Москве.\n\n'
            + CONNECTED_TEXT + '\n\n'
            'Выберите действие кнопками ниже. «Скачать всё» выгружает доступную '
            'историю подключённых источников. Баланс и текущие остатки сохраняются снимками.')


